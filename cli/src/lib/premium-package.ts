import { mkdirSync, writeFileSync, existsSync, readFileSync, rmSync } from "fs";
import { join, dirname } from "path";

/** npm package name for a server-delivered premium asset (compiled, not in public devkit bundle). */
export function premiumPackageName(assetId: string): string {
  return `@roboticela/premium-${assetId}`;
}

/** node_modules path segment for scoped premium package. */
export function premiumPackagePath(assetId: string): string {
  const name = premiumPackageName(assetId);
  return join("node_modules", ...name.split("/"));
}

export interface PremiumPackageManifest {
  name: string;
  version: string;
  type: "page" | "section" | "scaffold";
  exportName?: string;
  route?: string;
}

/**
 * Install server-signed compiled package into node_modules only.
 * Never writes TSX/source into the user's src/ tree.
 */
export function installPremiumPackageToNodeModules(
  assetId: string,
  files: Record<string, string>,
  manifest: PremiumPackageManifest,
  cwd: string
): string {
  const pkgName = premiumPackageName(assetId);
  const pkgRoot = join(cwd, premiumPackagePath(assetId));

  if (existsSync(pkgRoot)) {
    rmSync(pkgRoot, { recursive: true, force: true });
  }
  mkdirSync(pkgRoot, { recursive: true });

  const pkgJson =
    files["package.json"] ??
    JSON.stringify(
      {
        name: pkgName,
        version: manifest.version,
        private: true,
        type: "module",
        main: "./index.js",
        exports: { ".": "./index.js" },
        peerDependencies: {
          react: ">=18",
          "react-dom": ">=18",
          "@roboticela/devkit": ">=4.5.0",
        },
      },
      null,
      2
    );

  writeFileSync(join(pkgRoot, "package.json"), pkgJson);

  for (const [filename, content] of Object.entries(files)) {
    if (filename === "package.json") continue;
    const dest = join(pkgRoot, filename);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, content);
  }

  if (!existsSync(join(pkgRoot, "index.js"))) {
    throw new Error(`Premium package '${assetId}' missing compiled index.js from server.`);
  }

  return pkgName;
}

export interface PremiumImportEntry {
  assetId: string;
  packageName: string;
  route?: string;
  version: string;
}

/** Regenerate .devkit/premium-imports.ts — gitignored loader map (no source copies). */
export function writePremiumImportRegistry(entries: PremiumImportEntry[], cwd: string): void {
  const devkitDir = join(cwd, ".devkit");
  mkdirSync(devkitDir, { recursive: true });

  const lines = entries.map((e) => `  "${e.assetId}": () => import("${e.packageName}"),`);

  const content = `/** AUTO-GENERATED by @roboticela/devkit — do not edit */
import type { ComponentType } from "react";

export type PremiumImportFn = () => Promise<{ default: ComponentType }>;

export const premiumImports: Record<string, PremiumImportFn> = {
${lines.join("\n")}
};

export const premiumRoutes: Record<string, string> = {
${entries.map((e) => `  "${e.assetId}": ${JSON.stringify(e.route ?? e.assetId)},`).join("\n")}
};
`;

  writeFileSync(join(devkitDir, "premium-imports.ts"), content);

  writeFileSync(
    join(devkitDir, "premium-registry.json"),
    JSON.stringify(
      entries.map((e) => ({
        assetId: e.assetId,
        package: e.packageName,
        route: e.route ?? e.assetId,
        version: e.version,
        delivery: "server-package",
      })),
      null,
      2
    ) + "\n"
  );
}

export function readPremiumImportRegistry(cwd: string): PremiumImportEntry[] {
  const path = join(cwd, ".devkit", "premium-registry.json");
  if (!existsSync(path)) return [];
  const raw = JSON.parse(readFileSync(path, "utf-8")) as Array<{
    assetId: string;
    package: string;
    route?: string;
    version: string;
  }>;
  return raw.map((r) => ({
    assetId: r.assetId,
    packageName: r.package,
    route: r.route,
    version: r.version,
  }));
}

export function rebuildPremiumImportRegistry(cwd: string): void {
  const lockPath = join(cwd, "devkit.lock.json");
  if (!existsSync(lockPath)) return;
  const lock = JSON.parse(readFileSync(lockPath, "utf-8")) as {
    components?: Record<string, { version: string; resolved?: string }>;
  };
  const entries: PremiumImportEntry[] = [];
  for (const [assetId, entry] of Object.entries(lock.components ?? {})) {
    if (!entry.resolved?.startsWith("server-package:")) continue;
    entries.push({
      assetId,
      packageName: premiumPackageName(assetId),
      version: entry.version,
    });
  }
  if (entries.length > 0) writePremiumImportRegistry(entries, cwd);
}

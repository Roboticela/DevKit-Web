export function splitTokens(name: string): string[] {
  return name
    .replaceAll(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replaceAll(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .replaceAll(/([a-zA-Z])(\d)/g, '$1 $2')
    .replaceAll(/(\d)([a-zA-Z])/g, '$1 $2')
    .split(/[\s._-]+/)
    .filter(Boolean)
}

function stripKnown(name: string, pairs: [string, string][]): { rest: string; style?: string } {
  for (const [token, style] of pairs) {
    if (name.startsWith(token) && name.length > token.length) {
      return { rest: name.slice(token.length), style }
    }
  }
  return { rest: name }
}

function stripSuffix(name: string, pairs: [string, string][]): { rest: string; style?: string } {
  for (const [token, style] of pairs) {
    if (name.endsWith(token) && name.length > token.length) {
      return { rest: name.slice(0, -token.length), style }
    }
  }
  return { rest: name }
}

function parseOriginal(pack: string, original: string): { core: string; style?: string } {
  let rest = original
  let style: string | undefined
  const prefixes = PACK_PREFIX[pack] ?? []
  for (const [prefix, prefixStyle] of prefixes) {
    if (rest.startsWith(prefix) && rest.length > prefix.length) {
      rest = rest.slice(prefix.length)
      style = prefixStyle
      break
    }
  }

  const prefixed = stripKnown(rest, STYLE_PREFIX)
  rest = prefixed.rest
  style = prefixed.style ?? style

  const suffixed = stripSuffix(rest, STYLE_SUFFIX)
  rest = suffixed.rest
  style = suffixed.style ?? style

  if (!rest) rest = original
  return { core: rest, style }
}

function toPascal(value: string): string {
  const cleaned = value.replaceAll(/[^A-Za-z0-9]+/g, '')
  if (!cleaned) return 'Glyph'
  return cleaned[0].toUpperCase() + cleaned.slice(1)
}

export function iconSourceTokens(pack: string, original: string): {
  core: string
  style?: string
  words: string[]
} {
  const { core, style } = parseOriginal(pack, original)
  const expanded = expandCore(original, core)
  const seen = new Set<string>()
  const words: string[] = []
  for (const word of [...splitTokens(core), ...splitTokens(expanded)]) {
    const key = word.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    words.push(word)
  }
  return { core, style, words }
}

function expandCore(original: string, core: string): string {
  if (PHRASE[original]) return PHRASE[original]
  if (PHRASE[core]) return PHRASE[core]
  const tokens = splitTokens(core)
  if (tokens.length === 1) {
    return PHRASE[tokens[0]] ?? TOKEN[tokens[0]] ?? `${tokens[0]}IllustratedMark`
  }
  return tokens.map((token) => TOKEN[token] ?? PHRASE[token] ?? token).join('')
}

export function renameIcon(pack: string, original: string): string {
  const { core, style } = parseOriginal(pack, original)
  let body = expandCore(original, core)
  if (style && !body.includes(style)) body += style
  if (pack === 'si' && !body.includes('Brand')) body += 'BrandLogo'
  body = toPascal(body)
  if (!body.startsWith('Dk')) body = `Dk${body}`
  if (!/^[A-Za-z_][A-Za-z0-9]*$/.test(body)) body = `Dk${original.replaceAll(/[^A-Za-z0-9]/g, '')}`
  return body
}

export function remapPack<T>(pack: string, icons: Record<string, T>): Record<string, T> {
  const out: Record<string, T> = {}
  const used = new Set<string>()
  for (const [key, icon] of Object.entries(icons)) {
    let name = renameIcon(pack, key)
    let suffix = 2
    while (used.has(name)) {
      name = `${renameIcon(pack, key)}Variant${suffix}`
      suffix += 1
    }
    used.add(name)
    const named = icon as T & { displayName?: string }
    if (named && typeof named === 'object') named.displayName = name
    out[name] = icon
  }
  return out
}
